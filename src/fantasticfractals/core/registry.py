def get_fractal(fractal_id: str) -> FractalMeta:
    """Retrieve metadata for a fractal by ID, falling back to Mandelbrot."""
    return FRACTAL_REGISTRY.get(fractal_id.lower(), FRACTAL_REGISTRY["mandelbrot"])

def list_fractals() -> List[FractalMeta]:
    """Return list of all registered fractals."""
    return list(FRACTAL_REGISTRY.values())
